/**
 * @file test_net_time.c
 * @brief Host tests for the zone's UTC offset, in both units the system uses.
 *
 * The defect these exist for was found by reading on 2026-08-04 and confirmed
 * in a live board's `time_map`, which held four equivalences:
 *
 * ```
 * {"boot":1202,...,"utc_offset_min":-240}     laid down by a connected phone
 * {"boot":1202,...,"utc_offset_min":-240}
 * {"boot":1202,...,"utc_offset_min":-240}
 * {"boot":3395,...,"utc_offset_min":-14400}   laid down by SNTP, no phone
 * ```
 *
 * -240 minutes is EDT. -14400 is the same offset in *seconds*, sitting in a
 * field the page header, the wire protocol and the app all read as minutes. The
 * SNTP path handed the seconds function to a parameter named `utc_offset_min`,
 * and nothing anywhere refused it: it is a plain `int`, and -14400 fits the
 * int16 it was written into. A clockless session placed against that anchor
 * resolves to an offset of 240 hours - about ten days - rather than four.
 *
 * ## Why this can be a host test at all
 *
 * `net_time.c` is SNTP, NVS and `esp_timer` and does not compile here. The
 * offset arithmetic does, so it lives in `net_time_offset.c` and this suite
 * compiles that same translation unit - not a copy of it.
 *
 * ## What it is held to
 *
 * `WIRE_TIME_VECTORS`, generated by running the repository's real `wire.py`
 * against `zoneinfo`. So this is C's zone arithmetic checked against Python's
 * for the same instants, including both daylight changeovers, a leap day and
 * the epoch - and each instant now carries its offset in **both** units, which
 * is what makes a value that is wrong by a factor of sixty impossible to miss.
 *
 * The C side is given the same zone as a POSIX TZ string rather than an
 * Olson name, which is what the board itself is given (::NET_TIME_TZ_EASTERN)
 * and what newlib understands. It also means this suite needs no tzdata.
 *
 * Builds and runs on the host with no ESP-IDF: see the Makefile.
 */

#include <math.h> /* the generated header's power vectors use NAN and INFINITY */
#include <stdio.h>
#include <stdlib.h>
#include <time.h>

#include "net_time.h"
#include "wire_vectors_generated.h"

static int g_checks = 0;
static int g_failures = 0;

#define CHECK(cond, ...)                                                       \
    do {                                                                       \
        g_checks++;                                                            \
        if (!(cond)) {                                                         \
            g_failures++;                                                      \
            printf("  FAIL %s:%d: ", __FILE__, __LINE__);                      \
            printf(__VA_ARGS__);                                               \
            printf("\n");                                                      \
        }                                                                      \
    } while (0)

#define VECTOR_COUNT (sizeof(WIRE_TIME_VECTORS) / sizeof(WIRE_TIME_VECTORS[0]))

/** The widest offset any real zone has: UTC-12:00 to UTC+14:00, in minutes. */
#define MIN_ZONE_OFFSET_MIN (-12 * 60)
#define MAX_ZONE_OFFSET_MIN (14 * 60)

static void use_the_boards_zone(void)
{
    setenv("TZ", NET_TIME_TZ_EASTERN, 1);
    tzset();
}

/**
 * C's zone arithmetic against Python's, in seconds - the unit the formatters
 * take. This half was already right; it is here so that a divergence between
 * the two languages is told apart from a divergence between the two units.
 */
static void test_seconds_match_python(void)
{
    for (size_t i = 0; i < VECTOR_COUNT; i++) {
        const wire_time_vector_t *v = &WIRE_TIME_VECTORS[i];
        const int got = net_time_utc_offset_s(v->epoch_s);
        CHECK(got == v->utc_offset_s, "%s: %d s, zoneinfo said %d s", v->name, got,
              v->utc_offset_s);
    }
    printf("seconds: %zu instants agree with zoneinfo, both changeovers included\n",
           VECTOR_COUNT);
}

/**
 * The same instants in minutes - the unit everything that *records* an offset
 * carries. This is the check the defect walks into.
 */
static void test_minutes_match_python(void)
{
    for (size_t i = 0; i < VECTOR_COUNT; i++) {
        const wire_time_vector_t *v = &WIRE_TIME_VECTORS[i];
        const int got = net_time_utc_offset_min(v->epoch_s);
        CHECK(got == v->utc_offset_min, "%s: %d min, zoneinfo said %d min", v->name, got,
              v->utc_offset_min);
        CHECK(got * 60 == net_time_utc_offset_s(v->epoch_s),
              "%s: the two units disagree - %d min against %d s", v->name, got,
              net_time_utc_offset_s(v->epoch_s));
    }
    printf("minutes: %zu instants agree with zoneinfo\n", VECTOR_COUNT);
}

/**
 * The regression itself, stated as what it is: seconds are not minutes, and
 * every one of these instants is far enough from UTC to prove it. Were the
 * seconds function to be handed to a minutes field again - which is exactly
 * what `net_time.c` did - the value would leave the band a zone can occupy,
 * and this says so in the terms the board's own data showed it in.
 */
static void test_seconds_are_never_mistaken_for_minutes(void)
{
    for (size_t i = 0; i < VECTOR_COUNT; i++) {
        const wire_time_vector_t *v = &WIRE_TIME_VECTORS[i];
        const int minutes = net_time_utc_offset_min(v->epoch_s);
        const int seconds = net_time_utc_offset_s(v->epoch_s);

        CHECK(minutes >= MIN_ZONE_OFFSET_MIN && minutes <= MAX_ZONE_OFFSET_MIN,
              "%s: %d is outside anything a zone can be, in minutes", v->name, minutes);
        CHECK(seconds < MIN_ZONE_OFFSET_MIN || seconds > MAX_ZONE_OFFSET_MIN,
              "%s: %d s is small enough to pass for minutes, so this instant "
              "cannot catch the two being crossed", v->name, seconds);
        /* -14400 fits an int16 perfectly well, which is why the field's own
         * width caught nothing. Said out loud so nobody supposes it would. */
        CHECK((int)(int16_t)seconds == seconds,
              "%s: %d s no longer fits the int16 the anchor holds, so this "
              "check is no longer describing the defect", v->name, seconds);
    }
    printf("units: %zu instants where seconds could not be mistaken for a zone\n",
           VECTOR_COUNT);
}

/** EDT: the offset the board was actually holding when this was found. */
static void test_the_anchor_the_board_was_holding(void)
{
    /* 2026-08-01 15:45:12 -04:00, the "summer, EDT" vector. */
    const int64_t summer = 1785613512LL;

    CHECK(net_time_utc_offset_s(summer) == -14400, "EDT is not -14400 s: %d",
          net_time_utc_offset_s(summer));
    CHECK(net_time_utc_offset_min(summer) == -240, "EDT is not -240 min: %d",
          net_time_utc_offset_min(summer));

    /* The whole finding in one line: these are the same offset, and the board
     * recorded the first where it meant the second. */
    CHECK(net_time_utc_offset_s(summer) == net_time_utc_offset_min(summer) * 60,
          "the two readings of EDT are not the same offset");
    printf("EDT: -14400 s and -240 min are one offset, and only one of them is stored\n");
}

int main(void)
{
    printf("net_time: the zone's offset, in seconds and in minutes\n");
    use_the_boards_zone();
    test_seconds_match_python();
    test_minutes_match_python();
    test_seconds_are_never_mistaken_for_minutes();
    test_the_anchor_the_board_was_holding();

    printf("  %d checks, %d failures\n", g_checks, g_failures);
    return g_failures == 0 ? 0 : 1;
}
